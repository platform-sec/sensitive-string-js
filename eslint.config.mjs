import js from '@eslint/js';
import prettier from 'eslint-config-prettier';
import globals from 'globals';
import tseslint from 'typescript-eslint';

/**
 * Flat config, the only format ESLint 9 reads.
 *
 * The shape differs from the `.eslintrc.cjs` it replaces in one way worth
 * naming: an eslintrc applied to every file it was not told to ignore, whereas
 * a flat config applies a block only to the `files` it matches. The type-aware
 * rules therefore have to name the TypeScript glob explicitly, because
 * pointing them at a file missing from `tsconfig.eslint.json` is an error
 * rather than a skip.
 */
export default tseslint.config(
  {
    // Flat config has no `ignorePatterns`; a block holding only `ignores` is
    // the global ignore list, and it has to name build output that the old
    // `.eslintrc.cjs` never saw because eslintrc ignored `node_modules` and
    // dotfiles on its own.
    ignores: [
      '**/dist/**',
      '**/node_modules/**',
      '**/coverage/**',
      '**/codeql-db/**',
      // Prisma's generated client for the sensitive-prisma test schema. It is
      // regenerated by `pnpm build`, is not in the lint program, and type-aware
      // rules error rather than skip on a file a program does not contain.
      'packages/sensitive-prisma/generated/**',
      '**/*.js',
      '**/*.mjs',
      '**/*.cjs',
      '**/*.d.ts',
    ],
  },
  js.configs.recommended,
  ...tseslint.configs.recommendedTypeChecked,
  prettier,
  {
    files: ['**/*.ts'],
    languageOptions: {
      ecmaVersion: 2022,
      sourceType: 'module',
      globals: { ...globals.node, ...globals.es2022 },
      parserOptions: {
        // Two programs, not one per package. The workspace program is what
        // `tsconfig.eslint.json` describes and why; sensitive-nestjs needs
        // `experimentalDecorators` and so cannot share it.
        project: ['./tsconfig.eslint.json', './packages/sensitive-nestjs/tsconfig.eslint.json'],
        tsconfigRootDir: import.meta.dirname,
      },
    },
    rules: {
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_' },
      ],
      '@typescript-eslint/explicit-function-return-type': 'off',
      '@typescript-eslint/explicit-module-boundary-types': 'off',
      '@typescript-eslint/no-explicit-any': 'warn',
      // `sensitiveTemplate` is a tagged-template API, so a suite that calls one
      // purely to assert it throws is a real call, not a discarded expression.
      '@typescript-eslint/no-unused-expressions': ['error', { allowTaggedTemplates: true }],
      'no-console': 'warn',
    },
  },
  {
    // Fastify decides between callback style and promise style from the
    // function itself: `async` is the marker that selects promise style, and a
    // hook or handler written without it and without `done` stalls the request.
    // `require-await` therefore fires on code whose `async` is load bearing,
    // right across the package: the plugin function, whose async form is what
    // turns an option error into a rejected `register()`, and every route
    // handler in the suite. The hooks this package installs are callback style,
    // which is where the rule would have had something to say.
    files: ['packages/sensitive-fastify/**/*.ts'],
    rules: {
      '@typescript-eslint/require-await': 'off',
    },
  }
);
